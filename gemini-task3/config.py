"""Настройки эксперимента «Разные способы рассуждения»."""

# Модель (поддерживает thinking_level: minimal, low, medium, high; по умолчанию — minimal)
MODEL = "gemini-3.5-flash-lite"

# Уровни рассуждения (значения types.ThinkingLevel). thinking_budget не используется.
THINKING_LEVELS = ("MINIMAL", "HIGH")

# Способы решения
STRATEGIES = ("direct", "step_by_step", "prompt_generation", "expert_group")

STRATEGY_NAMES = {
    "direct": "Direct",
    "step_by_step": "Step-by-step",
    "prompt_generation": "Prompt generation",
    "expert_group": "Expert group",
}

# ---------- Темп и надёжность ----------

# Минимальный интервал между началами любых двух запросов (секунды).
# Бесплатный тариф: 5 запросов в минуту; попытки с ошибкой тоже засчитываются.
MIN_INTERVAL_BETWEEN_REQUESTS_SEC = 13

# Таймаут одного запроса (секунды). 180, а не 120: в задаче №2 один ответ gemini-3.5-flash-lite шёл 168 с
REQUEST_TIMEOUT_SEC = 180

# Временные ошибки, при которых запрос повторяется
RETRY_STATUS_CODES = (503, 504, 429)

# Паузы перед 1-м и 2-м повтором (секунды): максимум 1 + 2 = 3 попытки на вызов
RETRY_DELAYS_SEC = (15, 30)

# Для 429 «per minute» сервер подсказывает «retry in Ns»: ждём max(подсказка, пауза), но не дольше
MAX_RETRY_AFTER_SEC = 60

# Признаки исчерпания ДНЕВНОЙ квоты в тексте 429 — тогда эксперимент останавливается без повторов
DAILY_QUOTA_MARKERS = ("per day", "perday", "requests per day")

# ---------- Пилотный запуск ----------

PILOT_TASK_ID = "math_bat_ball"  # 1 задача × 4 способа × 2 уровня = 8 решений, 10 вызовов

# ---------- Промпты ----------

# Общий формат ответа — одинаковый для финальных вызовов всех четырёх способов.
ANSWER_FORMAT = (
    'Верни только JSON-объект вида {"answer": "короткий ответ", "explanation": "краткое объяснение"} '
    "без Markdown и без текста вне JSON."
)

# 1. Direct — только задача и общий формат ответа, без инструкций по рассуждению
DIRECT_TEMPLATE = "{question}\n\n{answer_format}"

# 2. Step-by-step
STEP_BY_STEP_TEMPLATE = (
    "{question}\n\n"
    "Решай задачу пошагово. Проверь результат перед ответом.\n\n"
    "{answer_format}"
)

# 3. Prompt generation — вызов 1: модель пишет промпт (обычный текст, без JSON-схемы)
PROMPT_GENERATION_TEMPLATE = (
    "Ты — эксперт по составлению промптов для языковых моделей. "
    "Составь эффективный промпт, который поможет языковой модели правильно решить задачу ниже. "
    "Не решай задачу и не указывай ответ. Верни только текст промпта.\n\n"
    "Задача:\n{question}"
)

# 3. Prompt generation — вызов 2: решение по сгенерированному промпту
PROMPT_GENERATION_SOLVE_TEMPLATE = (
    "{generated_prompt}\n\n"
    "Задача:\n{question}\n\n"
    "{answer_format}"
)

# 4. Expert group — три СИМУЛИРОВАННЫЕ роли в одном вызове одной модели
EXPERT_GROUP_TEMPLATE = (
    "Реши задачу, смоделировав обсуждение группы из трёх экспертов:\n"
    "1. Аналитик — разбирает условие, выделяет данные и то, что нужно найти.\n"
    "2. Инженер — строит и выполняет решение.\n"
    "3. Критик — ищет ошибки и ловушки в решении инженера.\n"
    "После обсуждения сформулируй согласованный итоговый ответ группы.\n\n"
    "Задача:\n{question}\n\n"
    "{answer_format} В поле explanation кратко изложи вклад каждой роли и итог."
)
